List<String> appSubCategories(String? mainCategory) {
  final normalized = mainCategory?.trim() ?? '';
  if (normalized.isEmpty || isGeneralCategory(normalized)) {
    return const [];
  }
  return appCategories[normalized] ?? const [];
}

bool isGeneralCategory(String? category) {
  return category == kGeneralCategory;
}

