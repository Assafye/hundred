int pointsForCategory({
  required String category,
  required String subCategory,
}) {
  final normalizedCategory = category.trim();
  final normalizedSubCategory = subCategory.trim();

  final categoryPoints = categorySubCategoryPoints[normalizedCategory];
  if (categoryPoints == null || categoryPoints.isEmpty) {
    return 0;
  }

  if (normalizedSubCategory.isNotEmpty &&
      categoryPoints.containsKey(normalizedSubCategory)) {
    return categoryPoints[normalizedSubCategory] ?? 0;
  }

  if (categoryPoints.containsKey('אחר')) {
    return categoryPoints['אחר'] ?? 0;
  }

  if (categoryPoints.containsKey('_default')) {
    return categoryPoints['_default'] ?? 0;
  }

  return 0;
}
