Future<void> _showLegalTextDialog(
  BuildContext context, {
  required String title,
  required String text,
}) async {
  final isLight = Theme.of(context).brightness == Brightness.light;

  await showDialog<void>(
    context: context,
    builder: (dialogContext) {
      final dialogWidth =
          (MediaQuery.of(dialogContext).size.width * 0.9).clamp(280.0, 560.0);
      return Directionality(
        textDirection: TextDirection.rtl,
        child: AlertDialog(
          backgroundColor: isLight ? Colors.white : const Color(0xFF101826),
          surfaceTintColor: Colors.transparent,
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(18),
          ),
          title: Text(
                              title,
            style: TextStyle(
              color: isLight ? Colors.black : Colors.white,
              fontWeight: FontWeight.w800,
              fontSize: 18,
            ),
          ),
          content: SizedBox(
            width: dialogWidth,
            child: SingleChildScrollView(
              child: SelectableText(
                                        text,
                textDirection: TextDirection.rtl,
                style: TextStyle(
                  color: isLight ? const Color(0xFF101826) : Colors.white,
                  height: 1.45,
                  fontSize: 14,
                ),
              ),
            ),
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.of(dialogContext).pop(),
              child: const Text('סגור'),
            ),
          ],
        ),
      );
    },
  );
}

